CREATE TABLE appartment_access_requests (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	creation_date DATE NOT NULL,
	status statuses NOT NULL,
	comment VARCHAR(300),
	appartment_id BIGINT REFERENCES appartments(id) NOT NULL,
	applicant_id BIGINT REFERENCES users(id) NOT NULL,
	CONSTRAINT unique_apartment_access_request UNIQUE(appartment_id, applicant_id)
);