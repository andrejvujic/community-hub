CREATE TABLE budget_category_balances (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    category budget_categories NOT NULL,
    neighborhood_id BIGINT REFERENCES neighborhoods(id) NOT NULL,
    total_amount NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    CONSTRAINT unique_category_per_neighborhood UNIQUE (category, neighborhood_id)
);