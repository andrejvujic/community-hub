CREATE TABLE community_events (
    id                   BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name                 VARCHAR(200) NOT NULL,
    description          VARCHAR(1000),
    event_date           DATE         NOT NULL,
    start_time           TIME         NOT NULL,
    duration_minutes     INT          NOT NULL CHECK (duration_minutes > 0),
    min_volunteers       INT          NOT NULL CHECK (min_volunteers > 0),
    status               event_statuses NOT NULL DEFAULT 'preparation',
    neighborhood_id      BIGINT REFERENCES neighborhoods(id) NOT NULL,
    organizer_citizen_id BIGINT REFERENCES citizens(id) NOT NULL
);