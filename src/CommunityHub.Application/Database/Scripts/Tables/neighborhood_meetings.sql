CREATE TABLE neighborhood_meetings (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    theme meeting_themes NOT NULL,
    meeting_time TIME NOT NULL,
    date_range_start DATE NOT NULL,
    date_range_end DATE NOT NULL,
    scheduled_date DATE,
    status meeting_statuses NOT NULL DEFAULT 'in_preparation',
    neighborhood_id BIGINT REFERENCES neighborhoods(id) NOT NULL,
    CONSTRAINT valid_meeting_range CHECK (date_range_end >= date_range_start),
    CONSTRAINT scheduled_date_required CHECK (
        (status = 'scheduled' AND scheduled_date IS NOT NULL) OR
        (status <> 'scheduled')
    )
);