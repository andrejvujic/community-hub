CREATE TABLE images (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	path VARCHAR(300) NOT NULL CHECK (path <> '') UNIQUE,
	building_id BIGINT REFERENCES buildings(id),
	neighborhood_id BIGINT REFERENCES neighborhoods(id),
	job_listing_id BIGINT REFERENCES job_listings(id),
	CONSTRAINT single_owner CHECK (
		(building_id IS NOT NULL AND neighborhood_id IS NULL AND job_listing_id IS NULL) OR
		(building_id IS NULL AND neighborhood_id IS NOT NULL AND job_listing_id IS NULL) OR
		(building_id IS NULL AND neighborhood_id IS NULL AND job_listing_id IS NOT NULL)
	)
);