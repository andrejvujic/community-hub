CREATE TYPE roles AS ENUM ('building_manager', 'building_resident', 'neighborhood_coordinator', 'citizen');
CREATE TYPE resources AS ENUM ('buildings', 'neighborhoods');
CREATE TYPE statuses AS ENUM ('waiting', 'accepted', 'rejected');

CREATE TABLE users (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(50) NOT NULL UNIQUE,
	user_role roles NOT NULL,
    password VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    surname VARCHAR(100) NOT NULL
);

CREATE TABLE countries (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(50) NOT NULL
);

CREATE TABLE cities (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(50) NOT NULL,
	country_id BIGINT REFERENCES countries(id) NOT NULL
);

CREATE TABLE streets(
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(100) NOT NULL,
	city_id BIGINT REFERENCES cities(id) NOT NULL,
	UNIQUE (name, city_id)
);

CREATE TABLE addresses (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	street_number VARCHAR(10) NOT NULL,
	neighborhood VARCHAR(100) NOT NULL,
	city_id BIGINT REFERENCES cities(id) NOT NULL,
	street_id BIGINT REFERENCES streets(id) NOT NULL
);

CREATE TABLE buildings (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	floor_count INT NOT NULL CHECK (floor_count > 0),
	building_manager_id BIGINT REFERENCES users(id) NOT NULL,
	address_id BIGINT REFERENCES addresses(id) NOT NULL
);

CREATE TABLE neighborhoods (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(50) NOT NULL,
	description VARCHAR(300) NOT NULL,
	budget INT DEFAULT 0 NOT NULL,
	city_id BIGINT REFERENCES cities(id) NOT NULL,
	coordinator_id BIGINT REFERENCES users(id) NOT NULL
);

CREATE TABLE images (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	path VARCHAR(300) NOT NULL UNIQUE,
	building_id BIGINT REFERENCES buildings(id),
	neighborhood_id BIGINT REFERENCES neighborhoods(id),
	CONSTRAINT single_owner CHECK (
		(building_id IS NOT NULL and neighborhood_id IS NULL) or
		(building_id IS NULL and neighborhood_id IS NOT NULL)
	)
);

CREATE TABLE apartments (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	apartment_number INT NOT NULL CHECK (apartment_number > 0),
	floor_number INT NOT NULL CHECK (floor_number > 0),
	building_id BIGINT REFERENCES buildings(id) NOT NULL
);

CREATE TABLE apartment_memberships (
	acceptance_date DATE NOT NULL,
	apartment_id BIGINT REFERENCES apartments(id) NOT NULL,
	building_resident_id BIGINT REFERENCES users(id) NOT NULL,
	PRIMARY KEY (apartment_id, building_resident_id)
);

CREATE TABLE apartment_access_requests (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	creation_date DATE NOT NULL,
	status statuses NOT NULL,
	comment VARCHAR(300),
	apartment_id BIGINT REFERENCES apartments(id) NOT NULL,
	applicant_id BIGINT REFERENCES users(id) NOT NULL,
	CONSTRAINT unique_apartment_access_request UNIQUE(apartment_id, applicant_id)
);

CREATE TABLE street_sections(
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	start_number INT DEFAULT 1 NOT NULL,
	end_number INT NOT NULL,
	street_id BIGINT REFERENCES streets(id) NOT NULL,
	neighborhood_id BIGINT REFERENCES neighborhoods(id) NOT NULL,
	side VARCHAR(10) NOT NULL DEFAULT 'both' CHECK (side IN ('even', 'odd', 'both'))
);

CREATE TABLE neighborhood_memberships (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	acceptance_date DATE NOT NULL,
	neighborhood_id BIGINT REFERENCES neighborhoods(id) NOT NULL
);

CREATE TABLE citizens (
    address_id BIGINT REFERENCES addresses(id) NOT NULL,
    membership_id BIGINT REFERENCES neighborhood_memberships(id) NOT NULL,
    PRIMARY KEY (id)
) INHERITS (users);

CREATE TABLE neighborhood_access_requests (
	citizen_id BIGINT REFERENCES citizens(id),
	neighborhood_id BIGINT REFERENCES neighborhoods(id),
	status statuses NOT NULL,
	creation_date DATE NOT NULL,
	comment VARCHAR(300),
	PRIMARY KEY (citizen_id, neighborhood_id)
);