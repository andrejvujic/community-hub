-- popravi gresku i pokusaj ponovo
BEGIN;

CREATE TYPE roles AS ENUM ('building_manager', 'building_resident', 'neighborhood_coordinator', 'citizen', 'neighborhood_service_provider');
CREATE TYPE statuses AS ENUM ('waiting', 'accepted', 'rejected');
CREATE TYPE parity_types AS ENUM ('even', 'odd', 'both');
CREATE TYPE billing_types AS ENUM ('per_hour', 'per_job');
CREATE TYPE rental_types AS ENUM ('one_day','multi_day');
CREATE TYPE common_room_rental_statuses AS ENUM ('waiting', 'waiting_date_change', 'rejected', 'approved');
CREATE TYPE ad_types AS ENUM('offer','request');
CREATE TYPE ad_categories AS ENUM('moving', 'cleaning', 'repairs', 'maintenance', 'borrowing', 'lending', 'delivery', 'shopping', 'tech_support', 'pet_care', 'child_care', 'elderly_care', 'gardening', 'tutoring', 'transport');
CREATE TYPE ad_statuses AS ENUM ('active','archived');

CREATE TABLE users (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(50) NOT NULL UNIQUE,
	user_role roles NOT NULL,
    password VARCHAR(50) NOT NULL,
    name VARCHAR(100) NOT NULL,
    surname VARCHAR(100) NOT NULL
);

CREATE TABLE countries (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(50) NOT NULL
);

CREATE TABLE cities (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(50) NOT NULL,
	country_id BIGINT REFERENCES countries(id) NOT NULL
);

CREATE TABLE streets (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(100) NOT NULL,
	city_id BIGINT REFERENCES cities(id) NOT NULL,
	UNIQUE (name, city_id)
);

CREATE TABLE addresses (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	street_number VARCHAR(10) NOT NULL,
	neighborhood VARCHAR(100) NOT NULL,
	city_id BIGINT REFERENCES cities(id) NOT NULL,
	street_id BIGINT REFERENCES streets(id) NOT NULL
);

CREATE TABLE buildings (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	floor_count INT NOT NULL CHECK (floor_count > 0),
    apartment_count INT NOT NULL CHECK (apartment_count > 0),
	building_manager_id BIGINT REFERENCES users(id) NOT NULL,
	address_id BIGINT REFERENCES addresses(id) NOT NULL
);

CREATE TABLE neighborhoods (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	name VARCHAR(50) NOT NULL,
	description VARCHAR(300) NOT NULL,
	budget INT DEFAULT 0 NOT NULL,
	city_id BIGINT REFERENCES cities(id) NOT NULL,
	coordinator_id BIGINT REFERENCES users(id) NOT NULL
);

CREATE TABLE apartments (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	apartment_number INT NOT NULL CHECK (apartment_number > 0),
	floor_number INT NOT NULL CHECK (floor_number > 0),
	building_id BIGINT REFERENCES buildings(id) NOT NULL
);

CREATE TABLE apartment_memberships (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	acceptance_date DATE NOT NULL,
	apartment_id BIGINT REFERENCES apartments(id) NOT NULL,
	building_resident_id BIGINT REFERENCES users(id) NOT NULL,
	CONSTRAINT unique_apartment_membership UNIQUE(apartment_id, building_resident_id)
);

CREATE TABLE apartment_access_requests (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	creation_date DATE NOT NULL,
	status statuses NOT NULL,
	comment VARCHAR(300),
	apartment_id BIGINT REFERENCES apartments(id) NOT NULL,
	applicant_id BIGINT REFERENCES users(id) NOT NULL
	-- CONSTRAINT unique_apartment_access_request UNIQUE(apartment_id, applicant_id)
);

CREATE TABLE common_rooms (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	building_id BIGINT REFERENCES buildings(id) NOT NULL,
	name VARCHAR(50) NOT NULL,
	description VARCHAR(200) NOT NULL,
	floor_number INT NOT NULL,
	rental_type rental_types NOT NULL
);
 
CREATE TABLE common_room_rental_requests (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	common_room_id BIGINT REFERENCES common_rooms(id) NOT NULL,
	start_date DATE NOT NULL,
	end_date DATE NOT NULL,
	rental_statuses common_room_rental_statuses NOT NULL,
	resident_id BIGINT REFERENCES users(id) NOT NULL,
	assigned_date DATE
);
 
CREATE TABLE ads (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	building_id BIGINT REFERENCES buildings(id) NOT NULL,
	resident_id BIGINT REFERENCES users(id) NOT NULL,
	ad_type ad_types NOT NULL,
	ad_category ad_categories NOT NULL,
	ad_status ad_statuses NOT NULL,
	description VARCHAR(200) NOT NULL,
	start_date DATE NOT NULL,
	end_date DATE NOT NULL
);
  
CREATE TABLE ad_time_slots (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	ad_id BIGINT REFERENCES ads(id) NOT NULL,
	start_time DATE NOT NULL,
	end_time DATE NOT NULL
);
 
CREATE TABLE ad_time_slot_reservations (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	offer_ad_time_slot_id BIGINT REFERENCES ad_time_slots(id) NOT NULL,
	request_ad_time_slot_id BIGINT REFERENCES ad_time_slots(id) NOT NULL
);

CREATE TABLE street_sections (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	start_number INT DEFAULT 1 NOT NULL,
	end_number INT NOT NULL,
	street_id BIGINT REFERENCES streets(id) NOT NULL,
	neighborhood_id BIGINT REFERENCES neighborhoods(id) NOT NULL,
	side parity_types NOT NULL DEFAULT 'both'
);

CREATE TABLE neighborhood_memberships (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	acceptance_date DATE NOT NULL,
	neighborhood_id BIGINT REFERENCES neighborhoods(id) NOT NULL
);

CREATE TABLE citizens (
    address_id BIGINT REFERENCES addresses(id) NOT NULL,
    membership_id BIGINT REFERENCES neighborhood_memberships(id),
    PRIMARY KEY (id)
) INHERITS (users);

CREATE TABLE neighborhood_access_requests (
	citizen_id BIGINT REFERENCES citizens(id),
	neighborhood_id BIGINT REFERENCES neighborhoods(id),
	status statuses NOT NULL,
	creation_date DATE NOT NULL,
	comment VARCHAR(300),
	PRIMARY KEY (citizen_id, neighborhood_id)
);

CREATE TABLE service_providers (
    id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    city_id BIGINT REFERENCES cities(id) NOT NULL,
    country_id BIGINT REFERENCES countries(id) NOT NULL
);

CREATE TABLE job_listings (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    service_name VARCHAR(150) NOT NULL,
    description VARCHAR(500) NOT NULL,
    billing_type billing_types NOT NULL,
    city_id BIGINT REFERENCES cities(id) NOT NULL,
    country_id BIGINT REFERENCES countries(id) NOT NULL,
    provider_id BIGINT REFERENCES service_providers(id) NOT NULL
);

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE price_entries (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    valid_from DATE NOT NULL,
    valid_to DATE NOT NULL,
    job_listing_id BIGINT REFERENCES job_listings(id) NOT NULL,
    CONSTRAINT valid_date_range CHECK (valid_to >= valid_from),
    CONSTRAINT no_overlapping_prices EXCLUDE USING gist (
        job_listing_id WITH =,
        daterange(valid_from, valid_to, '[]') WITH &&
    )
);

CREATE TABLE booked_jobs (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    scheduled_date DATE NOT NULL,
    scheduled_time TIME,
    duration_hours INT CHECK (duration_hours > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    is_substitution BOOLEAN NOT NULL DEFAULT FALSE,
    job_listing_id BIGINT REFERENCES job_listings(id) NOT NULL,
    neighborhood_id BIGINT REFERENCES neighborhoods(id) NOT NULL,
    substituting_provider_id BIGINT REFERENCES service_providers(id),
    CONSTRAINT substitution_consistency CHECK (
        (is_substitution = TRUE  AND substituting_provider_id IS NOT NULL) OR
        (is_substitution = FALSE AND substituting_provider_id IS NULL)
    ),
    CONSTRAINT time_and_duration_paired CHECK (
        (scheduled_time IS NULL) = (duration_hours IS NULL)
    )
);

CREATE TABLE leave_requests (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status statuses NOT NULL DEFAULT 'waiting',
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    provider_id BIGINT REFERENCES service_providers(id) NOT NULL,
    CONSTRAINT valid_leave_range CHECK (end_date >= start_date)
);

CREATE TABLE coverage_offers (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    status statuses NOT NULL DEFAULT 'waiting',
    leave_request_id BIGINT REFERENCES leave_requests(id) NOT NULL,
    booked_job_id BIGINT REFERENCES booked_jobs(id) NOT NULL,
    covering_provider_id BIGINT REFERENCES service_providers(id) NOT NULL,
    CONSTRAINT unique_coverage_offer UNIQUE (booked_job_id, covering_provider_id)
);

CREATE UNIQUE INDEX unique_accepted_coverage_per_job
    ON coverage_offers (booked_job_id)
    WHERE status = 'accepted';

CREATE TABLE provider_forums (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    is_closed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    created_by_id BIGINT REFERENCES service_providers(id) NOT NULL
);

CREATE TABLE forum_posts (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    content VARCHAR(2000) NOT NULL CHECK (content <> ''),
    posted_at TIMESTAMP NOT NULL DEFAULT NOW(),
    forum_id BIGINT REFERENCES provider_forums(id) NOT NULL,
    author_id BIGINT REFERENCES service_providers(id) NOT NULL
);

CREATE TABLE post_reactions (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    is_upvote BOOLEAN NOT NULL,
    post_id BIGINT REFERENCES forum_posts(id) NOT NULL,
    reactor_id BIGINT REFERENCES service_providers(id) NOT NULL,
    CONSTRAINT unique_reaction_per_provider UNIQUE (post_id, reactor_id)
);

CREATE TABLE provider_reviews (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    quality_rating SMALLINT NOT NULL CHECK (quality_rating BETWEEN 1 AND 5),
    communication_rating SMALLINT NOT NULL CHECK (communication_rating BETWEEN 1 AND 5),
    comment VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP,
    booked_job_id BIGINT REFERENCES booked_jobs(id) NOT NULL UNIQUE,
    coordinator_id BIGINT REFERENCES users(id) NOT NULL,
    CONSTRAINT updated_after_created CHECK (updated_at IS NULL OR updated_at >= created_at)
);

CREATE TABLE images (
	id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	path VARCHAR(300) NOT NULL CHECK (path <> ''), -- dok testiramo UNIQUE nije ukljucen
	building_id BIGINT REFERENCES buildings(id),
	neighborhood_id BIGINT REFERENCES neighborhoods(id),
	job_listing_id BIGINT REFERENCES job_listings(id),
	CONSTRAINT single_owner CHECK (
		(building_id IS NOT NULL AND neighborhood_id IS NULL AND job_listing_id IS NULL) OR
		(building_id IS NULL AND neighborhood_id IS NOT NULL AND job_listing_id IS NULL) OR
		(building_id IS NULL AND neighborhood_id IS NULL AND job_listing_id IS NOT NULL)
	)
);

COMMIT;